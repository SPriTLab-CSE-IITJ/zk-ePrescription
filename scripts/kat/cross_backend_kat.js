// Cross-backend known-answer tests (docs/protocol_specification.md Section 17).
//
//   node scripts/kat/cross_backend_kat.js prepare <workdir>
//       -> writes <workdir>/<set>.circom.json and
//          noir/cross_backend_kat/KAT_<set>.toml for every KAT set
//   node scripts/kat/cross_backend_kat.js compare <workdir>
//       -> reads <workdir>/<set>.circom.wtns.json and <workdir>/<set>.noir.out,
//          compares JS reference, Circom witness and Noir execution, writes
//          testdata/kat/cross_backend_kat_results.json, exits non-zero on any
//          mismatch.
//
// Driven by scripts/kat/run_cross_backend_kat.sh.

"use strict";

const fs = require("fs");
const path = require("path");

const REPO = path.resolve(__dirname, "../..");
const p2 = require(path.join(REPO, "circom/scripts/lib/poseidon2.js"));
const fixture = require(path.join(REPO, "testdata/kat/canonical_fixture.json"));
const permRef = require(path.join(REPO, "testdata/kat/poseidon2_permutation_reference.json"));

const hex = (x) => "0x" + BigInt(x).toString(16).padStart(64, "0");
const P = p2.P;

const OUTPUT_LAYOUT = [
    "perm[0]", "perm[1]", "perm[2]", "perm[3]",
    "Hraw(n=1)", "Hraw(n=2)", "Hraw(n=3)", "Hraw(n=4)", "Hraw(n=5)", "Hraw(n=6)", "Hraw(n=7)",
    "H1 commitment C", "H2 identity I", "H3 nullifier N", "H4 registry leaf L", "H5 Merkle node M", "H6 patient binding PB",
];

function kanSets() {
    const sc = fixture.scenario;
    const reg = fixture.registry;
    const d = reg.doctors;
    const base = {
        prescription_id: sc.prescription_id,
        medicine_code: sc.medicine_code,
        expiry: sc.expiry,
        threshold: sc.threshold,
        patient_secret: sc.patient_secret,
    };
    const docSet = (i, extra) => ({
        ...base,
        doctor_id: d[i].doctor_id,
        pubkey_x: d[i].pubkey_x,
        pubkey_y: d[i].pubkey_y,
        slot_index: "0",
        ...extra,
    });
    const sponge = (seed) => Array.from({ length: 7 }, (_, k) => String(BigInt(seed) + BigInt(k)));
    return {
        // Canonical fixture: C, I, N(slot 0), PB, leaf 0, node0 = H5(leaf0, leaf1)
        canonical: { perm_in: permRef.cases[0].input, sponge_in: sponge(1), ...docSet(0, { left: d[0].leaf_H4, right: d[1].leaf_H4 }) },
        // leaf 1, root = H5(node0, node1)
        doctor1: { perm_in: permRef.cases[1].input, sponge_in: sponge(100), ...docSet(1, { left: reg.nodes_H5.node0, right: reg.nodes_H5.node1, slot_index: "1" }) },
        // leaf 2, node1 = H5(leaf2, leaf3)
        doctor2: { perm_in: permRef.cases[2].input, sponge_in: sponge(1000), ...docSet(2, { left: d[2].leaf_H4, right: d[3].leaf_H4, slot_index: "2" }) },
        // leaf 3, order sensitivity H5(leaf1, leaf0)
        doctor3: { perm_in: permRef.cases[4].input, sponge_in: sponge(123456789), ...docSet(3, { left: d[1].leaf_H4, right: d[0].leaf_H4 }) },
        // Field edge values: every input p - 1
        edge: {
            perm_in: permRef.cases[3].input,
            sponge_in: Array(7).fill(hex(P - 1n)),
            prescription_id: hex(P - 1n), doctor_id: hex(P - 1n), medicine_code: hex(P - 1n),
            expiry: hex(P - 1n), threshold: hex(P - 1n), patient_secret: hex(P - 1n),
            slot_index: hex(P - 1n), pubkey_x: hex(P - 1n), pubkey_y: hex(P - 1n),
            left: hex(P - 1n), right: hex(P - 1n),
        },
        // Zero values
        zero: {
            perm_in: ["0", "0", "0", "0"], sponge_in: Array(7).fill("0"),
            prescription_id: "0", doctor_id: "0", medicine_code: "0", expiry: "0", threshold: "0",
            patient_secret: "0", slot_index: "0", pubkey_x: "0", pubkey_y: "0", left: "0", right: "0",
        },
    };
}

function jsExpected(s) {
    const b = (x) => BigInt(x);
    const perm = p2.permutation(s.perm_in.map(b));
    const sp = [];
    for (let n = 1; n <= 7; n++) sp.push(p2.hashRaw(s.sponge_in.slice(0, n).map(b)));
    const C = p2.H1(b(s.prescription_id), b(s.doctor_id), b(s.medicine_code), b(s.expiry), b(s.threshold));
    const I = p2.H2(b(s.patient_secret));
    return [
        ...perm, ...sp, C, I,
        p2.H3(b(s.patient_secret), C, b(s.slot_index)),
        p2.H4(b(s.doctor_id), b(s.pubkey_x), b(s.pubkey_y)),
        p2.H5(b(s.left), b(s.right)),
        p2.H6(I, C),
    ].map(hex);
}

function toToml(s) {
    const q = (x) => `"${x}"`;
    const lines = ["# GENERATED by scripts/kat/cross_backend_kat.js - do not edit by hand."];
    lines.push(`perm_in = [${s.perm_in.map(q).join(", ")}]`);
    lines.push(`sponge_in = [${s.sponge_in.map(q).join(", ")}]`);
    for (const k of ["prescription_id", "doctor_id", "medicine_code", "expiry", "threshold", "patient_secret", "slot_index", "pubkey_x", "pubkey_y", "left", "right"]) {
        lines.push(`${k} = ${q(s[k])}`);
    }
    return lines.join("\n") + "\n";
}

function toCircom(s) {
    const d = (x) => BigInt(x).toString();
    const o = { perm_in: s.perm_in.map(d), sponge_in: s.sponge_in.map(d) };
    for (const k of ["prescription_id", "doctor_id", "medicine_code", "expiry", "threshold", "patient_secret", "slot_index", "pubkey_x", "pubkey_y", "left", "right"]) {
        o[k] = d(s[k]);
    }
    return o;
}

function prepare(work) {
    fs.mkdirSync(work, { recursive: true });
    const sets = kanSets();
    for (const [name, s] of Object.entries(sets)) {
        fs.writeFileSync(path.join(work, `${name}.circom.json`), JSON.stringify(toCircom(s), null, 2));
        fs.writeFileSync(path.join(REPO, `noir/cross_backend_kat/KAT_${name}.toml`), toToml(s));
    }
    fs.writeFileSync(path.join(work, "sets.txt"), Object.keys(sets).join("\n") + "\n");
}

function parseNoir(txt) {
    const m = txt.match(/Circuit output: \[([^\]]*)\]/);
    if (!m) throw new Error("no Noir circuit output found");
    return m[1].split(",").map((x) => hex(BigInt(x.trim())));
}

function parseNoirScalar(txt) {
    const m = txt.match(/Circuit output: (0x[0-9a-fA-F]+)/);
    if (!m) throw new Error("no Noir scalar circuit output found");
    return hex(BigInt(m[1]));
}

function compare(work) {
    const sets = kanSets();
    const results = { _description: "Cross-backend KAT results: JS reference vs Circom witness vs Noir execution. Generated by scripts/kat/run_cross_backend_kat.sh.", sets: {}, summary: {} };
    let total = 0, pass = 0;

    // Permutation vs independent zkhash vectors
    const zk = {};
    for (const c of permRef.cases) zk[c.input.join(",")] = c.output;

    for (const [name, s] of Object.entries(sets)) {
        const exp = jsExpected(s);
        const w = require(path.resolve(work, `${name}.circom.wtns.json`));
        const circ = w.slice(1, 1 + OUTPUT_LAYOUT.length).map(hex);
        const noir = parseNoir(fs.readFileSync(path.join(work, `${name}.noir.out`), "utf8"));
        const ref = zk[s.perm_in.join(",")];
        const rows = OUTPUT_LAYOUT.map((label, i) => {
            const row = { construction: label, expected_js: exp[i], circom: circ[i], noir: noir[i] };
            if (i < 4 && ref) row.independent_reference = ref[i];
            row.equal = circ[i] === exp[i] && noir[i] === exp[i] && (!row.independent_reference || row.independent_reference === exp[i]);
            total++; if (row.equal) pass++;
            return row;
        });
        results.sets[name] = { inputs: s, results: rows };
        const bad = rows.filter((r) => !r.equal);
        console.log(`${name.padEnd(10)} ${rows.length - bad.length}/${rows.length} equal`);
        for (const r of bad) console.log(`   MISMATCH ${r.construction}: js=${r.expected_js} circom=${r.circom} noir=${r.noir}`);
    }

    // Registry generator (Noir) vs fixture
    const reg = fixture.registry;
    const regRows = [];
    for (let i = 0; i < 4; i++) {
        const out = parseNoir(fs.readFileSync(path.join(work, `registry_generator_${i}.noir.out`), "utf8"));
        // [selected_leaf, sibling0, sibling1, direction0, direction1, root]
        const d = reg.doctors[i];
        const exp = [d.leaf_H4, d.path_elements[0], d.path_elements[1], hex(d.path_indices[0]), hex(d.path_indices[1]), reg.root];
        const ok = exp.every((x, k) => x === out[k]);
        total++; if (ok) pass++;
        regRows.push({ doctor_index: i, expected: exp, noir_registry_generator: out, equal: ok });
        console.log(`registry_generator doctor ${i}: ${ok ? "equal" : "MISMATCH"}`);
    }
    results.registry_generator = regRows;

    // Issuance-side patient binding circuits (Circom 09 vs Noir patient_binding_issuance)
    {
        const w = require(path.resolve(work, "patient_binding.circom.wtns.json"));
        // Circom outputs: [patient_binding (I), patient_prescription_binding (PB)]
        const circomI = hex(w[1]);
        const circomPB = hex(w[2]);
        const noirPB = parseNoirScalar(fs.readFileSync(path.join(work, "patient_binding.noir.out"), "utf8"));
        const row = {
            expected_I: fixture.derived.identity_I, circom_I: circomI,
            expected_PB: fixture.derived.patient_binding_PB, circom_PB: circomPB, noir_PB: noirPB,
        };
        row.equal = circomI === row.expected_I && circomPB === row.expected_PB && noirPB === row.expected_PB;
        total++; if (row.equal) pass++;
        results.patient_binding_circuits = row;
        console.log(`patient binding circuits: ${row.equal ? "equal" : "MISMATCH " + JSON.stringify(row)}`);
    }

    results.summary = { compared: total, equal: pass, all_equal: total === pass };
    fs.writeFileSync(path.join(REPO, "testdata/kat/cross_backend_kat_results.json"), JSON.stringify(results, null, 2) + "\n");
    console.log(`TOTAL ${pass}/${total} equal`);
    if (pass !== total) process.exit(1);
}

const [cmd, work] = process.argv.slice(2);
if (cmd === "prepare") prepare(work);
else if (cmd === "compare") compare(work);
else { console.error("usage: cross_backend_kat.js prepare|compare <workdir>"); process.exit(2); }
