// Generates the canonical cross-backend application fixture
// (docs/protocol_specification.md, Sections 11.1 and 19) and every derived
// test vector for BOTH backends from one source of truth.
//
//   node circom/scripts/build_canonical_fixture.js
//
// Writes:
//   testdata/kat/canonical_fixture.json                 full fixture + derived values
//   circom/inputs/eprescription/canonical/*.json        Circom positive/negative inputs
//   circom/inputs/eprescription/patient_binding_issuance.json
//   noir/phase4_orchestrator/tests/positive/*.toml      Noir positive vectors
//   noir/phase4_orchestrator/tests/negative/*.toml      Noir negative vectors
//   noir/phase4_orchestrator/Prover.toml                (= TV-001)
//   noir/patient_binding_issuance/Prover.toml
//   noir/phase3_registry/tools/registry_generator/Prover.toml
//
// All values are computed here with the reference implementations in
// scripts/lib/ and are then checked against Noir execution and Circom
// witnesses by scripts/kat/run_cross_backend_kat.sh and the test suites.
// Every signature is verified off-circuit before it is written.
//
// TEST KEYS ONLY: doctor keys are sk * Generator for sk = 123..126
// (sk = 123 is the repository's pre-existing development key).

"use strict";

const fs = require("fs");
const path = require("path");
const p2 = require("./lib/poseidon2");
const { babyjub } = require("./lib/schnorr_bjj");

const ROOT = path.resolve(__dirname, "../..");
const hex = (x) => "0x" + BigInt(x).toString(16).padStart(64, "0");
const dec = (x) => BigInt(x).toString();

function write(rel, content) {
    const f = path.join(ROOT, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, content);
}

// ---------------------------------------------------------------------------
// Canonical scenario (spec Section 19)
// ---------------------------------------------------------------------------

const SCENARIO = {
    prescription_id: 1001n,
    doctor_id: 5001n,
    medicine_code: 123n,
    patient_secret: 12345n,
    expiry: 20261231n,
    threshold: 3n,
    // Single coherent verifier-supplied date for the whole fixture.
    current_date: 20260630n,
};

const DOCTORS = [
    { doctor_id: 5001n, sk: 123n },
    { doctor_id: 5002n, sk: 124n },
    { doctor_id: 5003n, sk: 125n },
    { doctor_id: 5004n, sk: 126n },
];

const DEPTH = 2;

function buildTree(leaves) {
    const levels = [leaves];
    while (levels[levels.length - 1].length > 1) {
        const cur = levels[levels.length - 1];
        const next = [];
        for (let i = 0; i < cur.length; i += 2) next.push(p2.H5(cur[i], cur[i + 1]));
        levels.push(next);
    }
    return levels;
}

function authPath(levels, index) {
    const elements = [];
    const indices = [];
    let idx = index;
    for (let lvl = 0; lvl < levels.length - 1; lvl++) {
        const isRight = idx % 2;
        indices.push(BigInt(isRight));
        elements.push(levels[lvl][isRight ? idx - 1 : idx + 1]);
        idx = Math.floor(idx / 2);
    }
    return { elements, indices };
}

function verifyPath(leaf, elements, indices, root) {
    let h = leaf;
    for (let i = 0; i < elements.length; i++) {
        h = indices[i] === 0n ? p2.H5(h, elements[i]) : p2.H5(elements[i], h);
    }
    return h === root;
}

// A logical redemption witness, independent of backend syntax.
function witness(base, over = {}) {
    return { ...base, ...over };
}

function toCircom(w) {
    return {
        prescription_id: dec(w.prescription_id),
        doctor_id: dec(w.doctor_id),
        medicine_code: dec(w.medicine_code),
        expiry: dec(w.expiry),
        threshold: dec(w.threshold),
        current_date: dec(w.current_date),
        patient_secret: dec(w.patient_secret),
        slot_index: dec(w.slot_index),
        pathElements: w.path_elements.map(dec),
        pathIndices: w.path_indices.map(dec),
        root: dec(w.root),
        PKx: dec(w.pk[0]),
        PKy: dec(w.pk[1]),
        Rx: dec(w.R[0]),
        Ry: dec(w.R[1]),
        s: dec(w.s),
    };
}

function toNoir(w, header) {
    const lines = [];
    lines.push(`# ${header}`);
    lines.push("# GENERATED by circom/scripts/build_canonical_fixture.js - do not edit by hand.");
    lines.push(`registry_root = "${hex(w.root)}"`);
    lines.push(`prescription_id = "${dec(w.prescription_id)}"`);
    lines.push(`doctor_id = "${dec(w.doctor_id)}"`);
    lines.push(`doctor_pubkey_x = "${hex(w.pk[0])}"`);
    lines.push(`doctor_pubkey_y = "${hex(w.pk[1])}"`);
    lines.push(`medicine_code = "${dec(w.medicine_code)}"`);
    lines.push(`quantity_threshold = "${dec(w.threshold)}"`);
    lines.push(`expiry_date = "${dec(w.expiry)}"`);
    lines.push(`current_date = "${dec(w.current_date)}"`);
    lines.push(`patient_secret = "${dec(w.patient_secret)}"`);
    lines.push(`slot_index = "${dec(w.slot_index)}"`);
    lines.push(`path_elements = [${w.path_elements.map((x) => `"${hex(x)}"`).join(", ")}]`);
    lines.push(`path_indices = [${w.path_indices.map((x) => `"${dec(x)}"`).join(", ")}]`);
    lines.push(`signature_nonce_x = "${hex(w.R[0])}"`);
    lines.push(`signature_nonce_y = "${hex(w.R[1])}"`);
    lines.push(`signature_s = "${hex(w.s)}"`);
    return lines.join("\n") + "\n";
}

async function main() {
    const sch = await babyjub();

    // ---- Doctor keys and registry ----------------------------------------
    const doctors = DOCTORS.map((d) => {
        const pk = sch.publicKey(d.sk);
        if (!sch.isValidPublicKey(pk)) throw new Error(`invalid PK for ${d.doctor_id}`);
        return { ...d, pk, leaf: p2.H4(d.doctor_id, pk[0], pk[1]) };
    });

    const levels = buildTree(doctors.map((d) => d.leaf));
    if (levels.length - 1 !== DEPTH) throw new Error("unexpected depth");
    const root = levels[DEPTH][0];
    const paths = doctors.map((d, i) => {
        const ap = authPath(levels, i);
        if (!verifyPath(d.leaf, ap.elements, ap.indices, root)) throw new Error("bad path");
        return ap;
    });

    // ---- Canonical prescription -------------------------------------------
    function prescriptionFor(docIndex, fields) {
        const d = doctors[docIndex];
        const C = p2.H1(fields.prescription_id, d.doctor_id, fields.medicine_code, fields.expiry, fields.threshold);
        const sig = sch.sign(d.sk, C);
        if (!sch.verify(d.pk, C, sig.R, sig.s)) throw new Error("signature self-check failed");
        return {
            prescription_id: fields.prescription_id,
            doctor_id: d.doctor_id,
            medicine_code: fields.medicine_code,
            expiry: fields.expiry,
            threshold: fields.threshold,
            current_date: fields.current_date,
            patient_secret: fields.patient_secret,
            slot_index: 0n,
            path_elements: paths[docIndex].elements,
            path_indices: paths[docIndex].indices,
            root,
            pk: d.pk,
            R: sig.R,
            s: sig.s,
            _C: C,
            _c: sig.c,
        };
    }

    const base = prescriptionFor(0, SCENARIO);
    const C = base._C;
    const I = p2.H2(SCENARIO.patient_secret);
    const PB = p2.H6(I, C);
    const N = (slot) => p2.H3(SCENARIO.patient_secret, C, slot);

    // ---- Positive vectors ---------------------------------------------------
    const doc3 = prescriptionFor(2, SCENARIO); // doctor 5003, leaf index 2
    const positives = [
        { id: "TV-001", desc: "canonical fixture, doctor 5001, slot 0", w: witness(base, { slot_index: 0n }) },
        { id: "TV-002", desc: "canonical fixture, slot 1 (distinct nullifier)", w: witness(base, { slot_index: 1n }) },
        { id: "TV-003", desc: "canonical fixture, slot 2 = threshold-1 (boundary)", w: witness(base, { slot_index: 2n }) },
        { id: "TV-004", desc: "canonical fixture, current_date == expiry (boundary)", w: witness(base, { current_date: SCENARIO.expiry }) },
        { id: "TV-005", desc: "same prescription fields issued by doctor 5003 (leaf index 2, path [0,1])", w: witness(doc3) },
    ];

    // ---- Negative vectors ---------------------------------------------------
    const l = sch.l;
    const P = p2.P;
    const otherC = prescriptionFor(0, { ...SCENARIO, medicine_code: 999n }); // valid signature over a different C
    const rogueSk = 999n;
    const roguePk = sch.publicKey(rogueSk);
    const rogueSig = sch.sign(rogueSk, C);
    // Doctor 5002's registry membership combined with a signature by doctor 5001's key
    // over the commitment that names doctor 5002.
    const C5002 = p2.H1(SCENARIO.prescription_id, 5002n, SCENARIO.medicine_code, SCENARIO.expiry, SCENARIO.threshold);
    const crossSig = sch.sign(123n, C5002);

    const offCurvePk = [base.pk[0], (base.pk[1] + 1n) % P];
    if (sch.inCurve(offCurvePk)) throw new Error("expected off-curve");
    const offCurveR = [base.R[0], (base.R[1] + 1n) % P];
    if (sch.inCurve(offCurveR)) throw new Error("expected off-curve");

    const negatives = [
        { id: "NT-001", desc: "invalid signature (s + 1)", w: witness(base, { s: (base.s + 1n) % l }) },
        { id: "NT-002", desc: "modified Merkle path element", w: witness(base, { path_elements: [base.path_elements[0] + 1n, base.path_elements[1]] }) },
        { id: "NT-003", desc: "expired prescription (current_date > expiry)", w: witness(base, { current_date: 20270101n }) },
        { id: "NT-004", desc: "slot_index == threshold", w: witness(base, { slot_index: SCENARIO.threshold }) },
        { id: "NT-005", desc: "modified medicine_code (commitment changes, signature fails)", w: witness(base, { medicine_code: 124n }) },
        { id: "NT-006", desc: "modified prescription_id", w: witness(base, { prescription_id: 1002n }) },
        { id: "NT-007", desc: "modified expiry (later date; commitment/signature fail)", w: witness(base, { expiry: 20271231n }) },
        { id: "NT-008", desc: "modified threshold (4; commitment/signature fail)", w: witness(base, { threshold: 4n }) },
        { id: "NT-009", desc: "modified doctor_id (5002) keeping doctor 5001 key, path and signature", w: witness(base, { doctor_id: 5002n }) },
        { id: "NT-010", desc: "registry public key replaced by doctor 5002's (valid, registered elsewhere) key", w: witness(base, { pk: doctors[1].pk }) },
        { id: "NT-011", desc: "doctor 5002 registry membership + signature by doctor 5001's key", w: witness(base, { doctor_id: 5002n, path_elements: paths[1].elements, path_indices: paths[1].indices, pk: doctors[0].pk, R: crossSig.R, s: crossSig.s }) },
        { id: "NT-012", desc: "doctor 5002 registry membership + doctor 5002 key + signature by doctor 5001's key", w: witness(base, { doctor_id: 5002n, path_elements: paths[1].elements, path_indices: paths[1].indices, pk: doctors[1].pk, R: crossSig.R, s: crossSig.s }) },
        { id: "NT-013", desc: "unregistered key with valid signature over C", w: witness(base, { pk: roguePk, R: rogueSig.R, s: rogueSig.s }) },
        { id: "NT-014", desc: "modified registry root", w: witness(base, { root: base.root + 1n }) },
        { id: "NT-015", desc: "flipped Merkle direction bit", w: witness(base, { path_indices: [1n - base.path_indices[0], base.path_indices[1]] }) },
        { id: "NT-016", desc: "non-binary Merkle direction (2)", w: witness(base, { path_indices: [2n, base.path_indices[1]] }) },
        { id: "NT-017", desc: "signature scalar s + l (satisfies equation mod l; must fail scalar bound)", w: witness(base, { s: base.s + l }) },
        { id: "NT-018", desc: "off-curve public key", w: witness(base, { pk: offCurvePk }) },
        { id: "NT-019", desc: "off-curve signature nonce R", w: witness(base, { R: offCurveR }) },
        { id: "NT-020", desc: "valid signature over a different commitment", w: witness(base, { R: otherC.R, s: otherC.s }) },
    ];

    // Sanity: the s + l malleability vector really satisfies the equation mod l,
    // so its rejection is due to the scalar bound alone.
    {
        const lhs = sch.bj.mulPointEscalar(sch.bj.Base8, base.s + l);
        const lhs0 = sch.bj.mulPointEscalar(sch.bj.Base8, base.s);
        if (!sch.F.eq(lhs[0], lhs0[0])) throw new Error("s + l check");
    }

    // ---- Write Circom inputs ------------------------------------------------
    for (const v of [...positives, ...negatives]) {
        write(`circom/inputs/eprescription/canonical/${v.id}.json`, JSON.stringify(toCircom(v.w), null, 2) + "\n");
    }

    // ---- Write Noir vectors -------------------------------------------------
    for (const v of positives) {
        write(`noir/phase4_orchestrator/tests/positive/${v.id}.toml`, toNoir(v.w, `${v.id}: ${v.desc}`));
    }
    for (const v of negatives) {
        write(`noir/phase4_orchestrator/tests/negative/${v.id}.toml`, toNoir(v.w, `${v.id}: ${v.desc}`));
    }
    write("noir/phase4_orchestrator/Prover.toml", toNoir(positives[0].w, `${positives[0].id}: ${positives[0].desc}`));

    // ---- Patient binding (issuance side) -----------------------------------
    write("noir/patient_binding_issuance/Prover.toml",
        "# Canonical fixture (docs/protocol_specification.md Section 19).\n" +
        "# GENERATED by circom/scripts/build_canonical_fixture.js - do not edit by hand.\n" +
        "# patient_secret: protocol-specific secret established at enrollment.\n" +
        `patient_secret = "${dec(SCENARIO.patient_secret)}"\n` +
        "# Canonical commitment C = H1(1001, 5001, 123, 20261231, 3)\n" +
        `commitment = "${hex(C)}"\n`);
    write("circom/inputs/eprescription/patient_binding_issuance.json",
        JSON.stringify({ patient_secret: dec(SCENARIO.patient_secret), commitment: dec(C) }, null, 2) + "\n");

    // ---- Noir registry generator input --------------------------------------
    let reg = "# Canonical four-doctor registry (docs/protocol_specification.md Section 11.1).\n" +
        "# GENERATED by circom/scripts/build_canonical_fixture.js - do not edit by hand.\n" +
        "# TEST KEYS ONLY: PK = sk * Generator, sk = 123, 124, 125, 126.\n";
    doctors.forEach((d, i) => {
        reg += `\n# Doctor ${i + 1} (sk = ${d.sk})\n`;
        reg += `doctor${i + 1}_id = "${dec(d.doctor_id)}"\n`;
        reg += `doctor${i + 1}_pubkey_x = "${hex(d.pk[0])}"\n`;
        reg += `doctor${i + 1}_pubkey_y = "${hex(d.pk[1])}"\n`;
    });
    reg += `\n# Authentication path target\ndoctor_index = "0"\n`;
    write("noir/phase3_registry/tools/registry_generator/Prover.toml", reg);

    // ---- Isolated signature-verifier vectors -------------------------------
    // Exercise the Schnorr verifier alone (no registry), so that each
    // rejection is attributable to the signature checks themselves.
    const lowOrderPk = [0n, 1n]; // identity: on curve, 8 * PK == identity
    const sigUnit = [
        { id: "SIG-OK", desc: "valid canonical signature", accept: true, pk: base.pk, C, R: base.R, s: base.s },
        { id: "SIG-BAD-S", desc: "s + 1", accept: false, noir: "returns_false", pk: base.pk, C, R: base.R, s: (base.s + 1n) % l },
        { id: "SIG-S-PLUS-L", desc: "s + l (equation holds mod l; scalar bound must reject)", accept: false, noir: "should_fail", pk: base.pk, C, R: base.R, s: base.s + l },
        { id: "SIG-OFFCURVE-PK", desc: "off-curve public key", accept: false, noir: "should_fail", pk: offCurvePk, C, R: base.R, s: base.s },
        { id: "SIG-OFFCURVE-R", desc: "off-curve nonce R", accept: false, noir: "should_fail", pk: base.pk, C, R: offCurveR, s: base.s },
        { id: "SIG-LOWORDER-PK", desc: "low-order public key (identity), 8*PK == O", accept: false, noir: "should_fail", pk: lowOrderPk, C, R: base.R, s: base.s },
        { id: "SIG-WRONG-C", desc: "valid signature verified against a different commitment", accept: false, noir: "returns_false", pk: base.pk, C: otherC._C, R: base.R, s: base.s },
        { id: "SIG-WRONG-PK", desc: "valid signature verified under doctor 5002's key", accept: false, noir: "returns_false", pk: doctors[1].pk, C, R: base.R, s: base.s },
    ];
    for (const v of sigUnit) {
        const ok = sch.inCurve(v.pk) && sch.inCurve(v.R) && sch.verify(v.pk, v.C, v.R, v.s);
        if (ok !== v.accept) throw new Error(`off-circuit expectation mismatch for ${v.id}`);
        write(`circom/inputs/unit/schnorr_canonical/${v.id}.json`, JSON.stringify({
            Rx: dec(v.R[0]), Ry: dec(v.R[1]), PKx: dec(v.pk[0]), PKy: dec(v.pk[1]), C: dec(v.C), s: dec(v.s),
        }, null, 2) + "\n");
    }
    let nt = "// GENERATED by circom/scripts/build_canonical_fixture.js - do not edit by hand.\n" +
        "//\n// Isolated Schnorr-verifier tests on the canonical fixture\n" +
        "// (docs/protocol_specification.md Section 13). Run with `nargo test`.\n\n" +
        "use crate::schnorr::verify_signature;\n";
    for (const v of sigUnit) {
        const fn = v.id.toLowerCase().replace(/-/g, "_");
        const attr = v.accept ? "#[test]" : (v.noir === "should_fail" ? "#[test(should_fail)]" : "#[test]");
        const call = `verify_signature(\n        ${hex(v.C)},\n        ${hex(v.pk[0])},\n        ${hex(v.pk[1])},\n        ${hex(v.R[0])},\n        ${hex(v.R[1])},\n        ${hex(v.s)},\n    )`;
        const body = v.accept ? `    assert(${call});` : (v.noir === "should_fail" ? `    let _ = ${call};` : `    assert(!${call});`);
        nt += `\n// ${v.id}: ${v.desc}\n${attr}\nfn ${fn}() {\n${body}\n}\n`;
    }
    write("noir/phase4_orchestrator/src/fixture_tests.nr", nt);

    // ---- Fixture record -----------------------------------------------------
    const fixture = {
        _description: "Canonical cross-backend fixture (docs/protocol_specification.md Sections 11.1, 19). Generated by circom/scripts/build_canonical_fixture.js.",
        scenario: Object.fromEntries(Object.entries(SCENARIO).map(([k, v]) => [k, dec(v)])),
        registry: {
            depth: DEPTH,
            doctors: doctors.map((d, i) => ({
                index: i,
                doctor_id: dec(d.doctor_id),
                test_secret_key: dec(d.sk),
                key_derivation: "PK = sk * Generator (circomlib); 8*PK = sk * Base8",
                pubkey_x: hex(d.pk[0]),
                pubkey_y: hex(d.pk[1]),
                leaf_H4: hex(d.leaf),
                path_elements: paths[i].elements.map(hex),
                path_indices: paths[i].indices.map(Number),
            })),
            nodes_H5: { node0: hex(levels[1][0]), node1: hex(levels[1][1]) },
            root: hex(root),
        },
        derived: {
            commitment_C: hex(C),
            identity_I: hex(I),
            patient_binding_PB: hex(PB),
            nullifier_slot0: hex(N(0n)),
            nullifier_slot1: hex(N(1n)),
            nullifier_slot2: hex(N(2n)),
            signature: {
                signer_doctor_id: "5001",
                Rx: hex(base.R[0]),
                Ry: hex(base.R[1]),
                s: hex(base.s),
                challenge_c: hex(base._c),
                nonce_derivation: "r = Hraw(0x6e6f6e6365, sk, C) mod l (fixture-only)",
                offcircuit_verified: true,
            },
        },
        expected_public_outputs: Object.fromEntries(positives.map((v) => {
            const Cv = p2.H1(v.w.prescription_id, v.w.doctor_id, v.w.medicine_code, v.w.expiry, v.w.threshold);
            return [v.id, {
                description: v.desc,
                commitment: hex(Cv),
                nullifier: hex(p2.H3(v.w.patient_secret, Cv, v.w.slot_index)),
                current_date: dec(v.w.current_date),
                registry_root: hex(v.w.root),
            }];
        })),
        negative_vectors: negatives.map((v) => ({ id: v.id, description: v.desc })),
    };
    write("testdata/kat/canonical_fixture.json", JSON.stringify(fixture, null, 2) + "\n");

    console.log("commitment C      :", hex(C));
    console.log("registry root     :", hex(root));
    console.log("nullifier (slot 0):", hex(N(0n)));
    console.log("doctor 5001 PK    :", hex(doctors[0].pk[0]), hex(doctors[0].pk[1]));
    console.log(`wrote ${positives.length} positive and ${negatives.length} negative vectors per backend`);
}

main().catch((e) => {
    console.error(e);
    process.exit(1);
});
