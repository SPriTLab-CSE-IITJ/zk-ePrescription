#!/usr/bin/env python3
"""Extract the BN254 Poseidon2 (t=4) constants used by Noir's
std::hash::poseidon2_permutation into poseidon2_constants.json.

Source file (fetch it first, pinned to the Nargo version in the Dockerfile):
  https://raw.githubusercontent.com/noir-lang/noir/v1.0.0-beta.24/acvm-repo/bn254_blackbox_solver/src/poseidon2_constants.rs

Usage:
  python3 extract_poseidon2_constants.py poseidon2_constants.rs > poseidon2_constants.json
"""
import json, re, sys

src = open(sys.argv[1]).read()
hexes = re.findall(r'field_from_hex\("([0-9a-fA-F]+)"\)', src)
assert len(hexes) == 4 + 64 * 4, len(hexes)
diag = ["0x" + h.lower() for h in hexes[:4]]
rc = [["0x" + h.lower() for h in hexes[4 + 4 * i: 8 + 4 * i]] for i in range(64)]
json.dump({
    "_provenance": "Extracted verbatim from noir-lang/noir tag v1.0.0-beta.24, "
                   "acvm-repo/bn254_blackbox_solver/src/poseidon2_constants.rs "
                   "(the solver for std::hash::poseidon2_permutation). Generated by "
                   "circom/scripts/lib/extract_poseidon2_constants.py. Do not edit by hand.",
    "field": "BN254 scalar field", "t": 4, "rounds_f": 8, "rounds_p": 56, "sbox": "x^5",
    "internal_matrix_diagonal": diag, "round_constants": rc,
}, sys.stdout, indent=1)
print()
